def leverage_correlation(returns: np.ndarray) -> float:
    """rho(r_t, |r_{t+1}|) — negative value indicates the leverage effect."""
    r, ar = returns[:-1], np.abs(returns[1:])
    if len(r) < 2:
        return np.nan
    return float(np.corrcoef(r, ar)[0, 1])


def compute_fingerprint(
    series: pd.Series,
    name: str,
    n_lags_acf: int = 100,
    lb_lags: int = 20,
    macro: bool = False,
) -> dict:
    """
    Compute the standard fingerprint for one transformed series.

    Keys: name, n_obs, mean, std, skewness, excess_kurtosis,
          acf_abs_returns, ljung_box_stat, ljung_box_pval, leverage_corr.

    Parameters
    ----------
    macro : bool
        Financial series have thousands of observations, so the ACF (100 lags)
        and Ljung-Box (20 lags) defaults are fine. Macro series can be very
        short (US quarterly GDP growth is ~310 points; windowed even fewer),
        so when macro=True the lag counts are capped to a safe fraction of the
        sample to avoid statsmodels errors. The leverage effect and ARCH test
        are financial-volatility concepts with little meaning for, e.g., GDP
        growth — they are still computed (they will not error) but interpret
        them with care for macro series.
    """
    vals = series.dropna().values.astype(float)
    n = len(vals)

    if macro:
        # Cap lags so we never request more than the sample can support.
        n_lags_acf = max(1, min(n_lags_acf, n // 2 - 1))
        lb_lags = max(1, min(lb_lags, n // 5))

    fp = {
        "name":            name,
        "n_obs":           n,
        "mean":            float(np.mean(vals)),
        "std":             float(np.std(vals, ddof=1)),
        "skewness":        float(stats.skew(vals)),
        "excess_kurtosis": float(stats.kurtosis(vals)),
        "acf_abs_returns": acf(np.abs(vals), nlags=n_lags_acf, fft=True)[1:],
        "leverage_corr":   leverage_correlation(vals),
    }
    lb_res = acorr_ljungbox(vals ** 2, lags=[lb_lags], return_df=True)
    fp["ljung_box_stat"] = float(lb_res["lb_stat"].iloc[-1])
    fp["ljung_box_pval"] = float(lb_res["lb_pvalue"].iloc[-1])
    return fp


