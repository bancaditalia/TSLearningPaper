def window_for(name: str) -> "tuple[int, int]":
    """Return (window_len, step) for a series, from the config.
    Looks up the series' frequency, then that frequency's window settings.

        window_for("Bitcoin")      -> (50, 1)
        window_for("US_GDP")       -> (8, 1)
    """
    freq = CFG["series_freq"][name]
    w = CFG["windows"][freq]
    return w["length"], w["step"]


