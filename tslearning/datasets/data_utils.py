def plot_kde(ax, data, label, color, lw=1.5):
    """Plot a KDE curve on a given axis."""
    kde = gaussian_kde(data)
    x = np.linspace(np.percentile(data, 1), np.percentile(data, 99), 300)
    ax.plot(x, kde(x), label=label, color=color, lw=lw)


def plot_comparison(real_vals, synthetic_windows, title):
    """
    Standard 3-panel comparison plot:
    KDE distribution, ACF of |values|, Q-Q vs normal.
    Works for any dataset — financial or otherwise.
    """
    synthetic_long = synthetic_windows.flatten()
    real_long      = real_vals.flatten()

    fig, axes = plt.subplots(1, 3, figsize=(18, 4))
    fig.suptitle(title, fontsize=14, fontweight="bold")

    # 1. KDE distribution
    plot_kde(axes[0], real_long, "Real", "black", lw=2)
    plot_kde(axes[0], synthetic_long, "Synthetic", "blue")
    axes[0].set_title("Distribution")
    axes[0].set_xlim(np.percentile(real_long, 1), np.percentile(real_long, 99))
    axes[0].legend()

    # 2. ACF of |values|
    n_lags = 100
    lags   = np.arange(1, n_lags + 1)
    axes[1].bar(lags, acf(np.abs(real_long), nlags=n_lags, fft=True)[1:],
                alpha=0.7, label="Real", color="black")
    axes[1].bar(lags, acf(np.abs(synthetic_long), nlags=n_lags, fft=True)[1:],
                alpha=0.7, label="Synthetic", color="blue")
    axes[1].set_title("ACF of |values|")
    axes[1].legend()

    # 3. Q-Q vs normal
    (osm_real, osr_real), _ = stats.probplot(real_long, dist="norm")
    axes[2].scatter(osm_real, osr_real, s=2, alpha=0.3, color="black", label="Real")
    (osm_syn, osr_syn), (slope, intercept, _) = stats.probplot(synthetic_long, dist="norm")
    axes[2].scatter(osm_syn, osr_syn, s=2, alpha=0.3, color="blue", label="Synthetic")
    ref = np.array([osm_real[0], osm_real[-1]])
    axes[2].plot(ref, slope * ref + intercept, color="red", lw=1.5)
    axes[2].set_title("Q-Q vs Normal")
    axes[2].legend()

    plt.tight_layout()
    plt.show()


def compare_fingerprints(real_vals, synthetic_windows, dataset_name):
    """
    Print a fingerprint comparison table between real and synthetic data.
    Includes ratio column — 1.0 is perfect.
    """
    real_long  = real_vals.flatten()
    synth_long = synthetic_windows.flatten()

    real_fp = {
        "excess_kurtosis": stats.kurtosis(real_long),
        "skewness":        stats.skew(real_long),
        "std":             np.std(real_long, ddof=1),
        "leverage_corr":   np.corrcoef(real_long[:-1], np.abs(real_long[1:]))[0, 1],
    }
    synth_fp = {
        "excess_kurtosis": stats.kurtosis(synth_long),
        "skewness":        stats.skew(synth_long),
        "std":             np.std(synth_long, ddof=1),
        "leverage_corr":   np.corrcoef(synth_long[:-1], np.abs(synth_long[1:]))[0, 1],
    }

    print(f"\n{dataset_name}")
    print(f"{'Metric':20s}  {'Real':>10s}  {'Synthetic':>10s}  {'Ratio':>10s}")
    print("-" * 55)
    for k in real_fp:
        ratio = synth_fp[k] / real_fp[k] if real_fp[k] != 0 else float("inf")
        print(f"{k:20s}  {real_fp[k]:>10.4f}  {synth_fp[k]:>10.4f}  {ratio:>10.2f}")


def quick_fp(paths, keys):
    """
    Fast fingerprint computation across many synthetic paths.
    Averages stats over all paths rather than computing on flattened array.
    """
    result = {}
    if "excess_kurtosis" in keys:
        result["excess_kurtosis"] = np.mean([stats.kurtosis(p) for p in paths])
    if "skewness" in keys:
        result["skewness"] = np.mean([stats.skew(p) for p in paths])
    if "std" in keys:
        result["std"] = np.mean([np.std(p, ddof=1) for p in paths])
    if "leverage_corr" in keys:
        result["leverage_corr"] = np.mean([
            np.corrcoef(p[:-1], np.abs(p[1:]))[0, 1] for p in paths
        ])
    return result


def merge_into_pickle(path, new: dict) -> dict:
    """Update the per-series dict stored at `path` with `new`, keeping every other entry.

    The ingestion stages used to write their pkl files from scratch with only the series
    of the current run, so `data_prep.py --series SP500,Gold` deleted Bitcoin, NASDAQ, …
    from transformed.pkl for every later step. Returns the merged dict (also written).
    """
    import pickle
    from pathlib import Path

    path = Path(path)
    merged = {}
    if path.exists():
        with open(path, "rb") as f:
            old = pickle.load(f)
        if isinstance(old, dict):
            merged.update(old)
    merged.update(new)
    with open(path, "wb") as f:
        pickle.dump(merged, f)
    return merged
