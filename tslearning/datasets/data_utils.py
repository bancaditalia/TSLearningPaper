def log_returns(price_series: pd.Series) -> pd.Series:
    """Compute log-returns r_t = ln(P_t / P_{t-1})."""
    return np.log(price_series / price_series.shift(1)).dropna()


def log_level(series: pd.Series) -> pd.Series:
    """Apply log transform (no differencing)."""
    return np.log(series.astype(float))


def macro_transform(series: pd.Series, kind: str) -> pd.Series:
    """
    Apply the indicator-appropriate transform to a macro series.

    kind
    ----
    'logdiff' : growth rate of a positive level (GDP, CPI, M2, credit).
                ln(x_t / x_{t-1}) — the macro analogue of a log-return.
    'diff'    : first difference of a rate/percentage (unemployment, policy
                rate). x_t - x_{t-1}. Log-diff is wrong here: a rate is already
                a percentage and does not grow multiplicatively.
    'log'     : log-level, no differencing.
    'level'   : raw values, untouched.
    """
    s = series.astype(float).dropna()
    if kind == "logdiff":
        return np.log(s / s.shift(1)).dropna()
    elif kind == "diff":
        return s.diff().dropna()
    elif kind == "log":
        return np.log(s)
    elif kind == "level":
        return s
    else:
        raise ValueError(f"Unknown transform: {kind}")


