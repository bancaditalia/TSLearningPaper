def make_windows(
    series: "pd.Series | np.ndarray",
    window_len: int,
    step: int = 1,
    split: str = "fraction",
    train: "tuple[str, str] | None" = None,
    test: "tuple[str, str] | None" = None,
    train_frac: float = 0.8,
) -> "tuple[np.ndarray, np.ndarray]":
    """
    Slice a 1-D time series into overlapping windows, split into train/test.

    `split` selects the split method:
      * "fraction" (DEFAULT): use ALL windows (full history) and cut the first
        `train_frac` chronologically into train, the rest into test. This is
        what the synthesizers use — every available window, every dataset.
      * "date": split by CALENDAR DATE using `train`/`test` (start, end) date
        strings, defaulting to the `split` section of configs/config.yaml. A
        window goes to train if it lies entirely inside the train dates, to
        test if entirely inside the test dates, and is DROPPED if it straddles
        the gap (prevents leakage). This is only for the classifier's real
        Bitcoin-relationship input, not for synthesizer training. Falls back to
        the fractional split if the series has no dates or no date overlap.

    Returns
    -------
    train_windows, test_windows : np.ndarray of shape (n, window_len)
    """
    has_dates = isinstance(series, pd.Series) and isinstance(
        series.index, pd.DatetimeIndex
    )
    if isinstance(series, pd.Series):
        s = series.dropna()
        vals = s.values.astype(float)
        dates = s.index if has_dates else None
    else:
        vals = np.asarray(series, dtype=float)
        dates = None

    n = len(vals)
    if n < window_len:
        empty = np.empty((0, window_len), dtype=float)
        return empty, empty

    starts = list(range(0, n - window_len + 1, step))
    windows = np.stack([vals[i : i + window_len] for i in starts])

    # ── Date-based split (only when explicitly requested) ─────────────────────
    if split == "date" and dates is not None:
        train = train or CFG["split"]["train"]
        test = test or CFG["split"]["test"]
        tr0, tr1 = pd.Timestamp(train[0]), pd.Timestamp(train[1])
        te0, te1 = pd.Timestamp(test[0]),  pd.Timestamp(test[1])

        train_idx, test_idx = [], []
        for row, i in enumerate(starts):
            w_start, w_end = dates[i], dates[i + window_len - 1]
            if w_start >= tr0 and w_end <= tr1:
                train_idx.append(row)
            elif w_start >= te0 and w_end <= te1:
                test_idx.append(row)
            # else: straddles the train/test gap -> dropped

        # If the series' dates don't overlap the configured split at all
        # (e.g. the seasonal datasets: Airline 1949–60, Electricity 2000),
        # fall back to the fractional split rather than return nothing.
        if train_idx or test_idx:
            return windows[train_idx], windows[test_idx]
        warnings.warn(
            "Series dates do not overlap the configured train/test window; "
            "falling back to a fractional split."
        )

    # ── Fractional fallback (no dates, or no date overlap) ────────────────────
    split = int(len(windows) * train_frac)
    return windows[:split], windows[split:]


def synth_windows(series, window_len: int, step: int = 1):
    """Train/test windows for the GENERATIVE models (DDPM), without test-period leakage.

    config `synth.split`:
      "date" (default)  train = every window that ends before the test period starts
                        (or before `synth.train_until`, if set): all earlier history is
                        used, nothing from the test period. test = windows inside
                        `split.test`.
      "fraction"        the old behaviour: first 80% of each series' windows. With
                        Bitcoin (from 2017) that reached into 2023, i.e. into the
                        2022-2024 test period — kept only to reproduce old samples.
    """
    sc = CFG.get("synth") or {}
    if sc.get("split", "date") == "fraction":
        return make_windows(series, window_len, step)
    test = CFG["split"]["test"]
    until = sc.get("train_until") or str(
        (pd.Timestamp(test[0]) - pd.Timedelta(days=1)).date())
    return make_windows(series, window_len, step, split="date",
                        train=("1800-01-01", until), test=tuple(test))


def zscore_window(w, eps: float = 1e-8) -> np.ndarray:
    """Per-window z-score: (w - mean) / std. Removes scale, keeps shape.
    Self-contained (each window uses its own stats), so it's identical at
    train and inference time — no fitted parameters, no leakage.
    Apply ONLY to the classifier input, never before the reasoner."""
    w = np.asarray(w, dtype=float)
    return (w - w.mean()) / (w.std() + eps)


def build_pair_input(pair_names, lookup, standardize: bool = True) -> np.ndarray:
    """Concatenate the two windows of each pair into the classifier input
    of shape (n_pairs, 2*L). If `standardize`, each window is z-scored on its
    own first (§4.3 per-pair standardisation)."""
    z = zscore_window if standardize else (lambda x: np.asarray(x, dtype=float))
    return np.array([np.concatenate([z(lookup[a]), z(lookup[b])])
                     for a, b in pair_names])


def build_pair_cnn(pair_names, lookup, standardize: bool = True) -> np.ndarray:
    """Classifier input for the 2-channel model V7: shape (n_pairs, 2, L).
    Each window is z-scored on its own, then the two windows are stacked as
    channels (channel 0 = first series, channel 1 = second)."""
    z = zscore_window if standardize else (lambda w: np.asarray(w, dtype=float))
    return np.stack([np.stack([z(lookup[a]), z(lookup[b])], axis=0)
                     for a, b in pair_names]).astype(np.float32)


def normalise_windows(windows: np.ndarray, method: str = "zscore") -> np.ndarray:
    """
    Normalise each window independently.
    method: 'zscore' (zero-mean, unit-var) or 'minmax' ([0, 1]).
    """
    out = np.empty_like(windows)
    for i, w in enumerate(windows):
        if method == "zscore":
            mu, sigma = w.mean(), w.std() + 1e-8
            out[i] = (w - mu) / sigma
        elif method == "minmax":
            lo, hi = w.min(), w.max() + 1e-8
            out[i] = (w - lo) / (hi - lo)
        else:
            raise ValueError(f"Unknown method: {method}")
    return out


