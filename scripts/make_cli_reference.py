#!/usr/bin/env python3
"""
Write SCRIPTS.md: the `--help` of every script in scripts/, i.e. every option with its
default, collected in one file. Rerun after changing a script's options.

    python scripts/make_cli_reference.py
"""
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKIP = {"_cli.py", "make_cli_reference.py"}

# the order of the pipeline first, then the rest alphabetically
ORDER = ["data_prep.py", "synthesize.py", "build_realistic_transfer.py", "distill.py",
         "prep_real_pairs.py", "infer.py", "generate_rules.py", "verify_rules.py", "eval.py",
         "llm_rules.py", "simulate_rules.py", "multiple_testing.py", "paper.py",
         "paper_final.py", "runs.py"]


def main():
    scripts = sorted(p.name for p in (ROOT / "scripts").glob("*.py") if p.name not in SKIP)
    scripts = [s for s in ORDER if s in scripts] + [s for s in scripts if s not in ORDER]
    out = ["# Scripts and their options", "",
           "Generated by `python scripts/make_cli_reference.py` from each script's `--help`.",
           "Every script also takes `--run <run>` (see README, Runs).", ""]
    out += [f"- [`{s}`](#{s.replace('.', '')})" for s in scripts]
    failed = []
    for s in scripts:
        r = subprocess.run([sys.executable, str(ROOT / "scripts" / s), "--help"],
                           capture_output=True, text=True, cwd=ROOT)
        text = r.stdout.strip() if r.returncode == 0 else ""
        text = text.replace(str(ROOT) + "/", "").replace(str(ROOT), ".")   # no local paths
        if not text:
            failed.append(s)
            text = "(--help failed: " + (r.stderr.strip().splitlines() or ["?"])[-1] + ")"
        out += ["", f"## {s}", "", "```", text, "```"]
    (ROOT / "SCRIPTS.md").write_text("\n".join(out) + "\n")
    print(f"SCRIPTS.md: {len(scripts)} scripts" + (f"; --help failed for {failed}" if failed else ""))


if __name__ == "__main__":
    main()
